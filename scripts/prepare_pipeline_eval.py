#!/usr/bin/env python3
"""Build a reproducible 100-claim grounding benchmark from HealthVer test data.

This is a verifier/grounding benchmark: the HealthVer claim is used as the
atomic claim and its gold evidence is retained. It does not pretend that the
claim was generated by MedGemma; a separate generated-answer benchmark should
be annotated when measuring the full LLM pipeline.
"""
import argparse, json, shutil
from pathlib import Path
from sklearn.feature_extraction.text import TfidfVectorizer
from sklearn.metrics.pairwise import linear_kernel
from medgemma_multivers_pipeline import semantic_scores


def read(path):
    return [json.loads(x) for x in Path(path).open(encoding="utf-8")]


def write(rows, path):
    with Path(path).open("w", encoding="utf-8") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--claims", default="data_train/target/healthver/claims_test.jsonl")
    ap.add_argument("--corpus", default="data_train/target/healthver/corpus.jsonl")
    ap.add_argument("--output_dir", default="results/pipeline_eval_100")
    ap.add_argument("--n", type=int, default=100)
    ap.add_argument("--top_k_docs", type=int, default=10)
    ap.add_argument("--retrieval", choices=["tfidf", "semantic"], default="tfidf")
    ap.add_argument("--semantic_model", default="pritamdeka/S-PubMedBert-MS-MARCO")
    args = ap.parse_args()
    out = Path(args.output_dir); out.mkdir(parents=True, exist_ok=True)
    source_claims, corpus = read(args.claims), read(args.corpus)
    source_claims = source_claims[:args.n]
    texts = [x["title"] + " " + " ".join(x["abstract"]) for x in corpus]
    ids = [int(x["doc_id"]) for x in corpus]
    vec = TfidfVectorizer(stop_words="english"); matrix = vec.fit_transform(texts)
    sem = None
    if args.retrieval == "semantic":
        sem = semantic_scores([x["claim"].strip() for x in source_claims], texts,
                              args.semantic_model, "cuda" if __import__("torch").cuda.is_available() else "cpu")
    model_claims, annotations = [], []
    for new_id, row in enumerate(source_claims):
        claim = row["claim"].strip()
        scores = (sem[new_id] if sem is not None else
                  linear_kernel(vec.transform([claim]), matrix).ravel())
        ix = scores.argsort()[::-1][:args.top_k_docs]
        gold_evidence = [{"doc_id": int(doc), "sentences": [int(s)]}
                         for doc, evs in row.get("evidence", {}).items()
                         for ev in evs for s in ev.get("sentences", [])]
        labels = [ev["label"] for evs in row.get("evidence", {}).values() for ev in evs]
        gold_label = max(set(labels), key=labels.count) if labels else "NEI"
        model_claims.append({"id": new_id, "claim": claim,
                             "doc_ids": [ids[i] for i in ix],
                             "retrieval": args.retrieval,
                             "retrieval_scores": [float(scores[i]) for i in ix]})
        annotations.append({
            "claim_id": new_id,
            "question": "Evaluate this medical claim against the biomedical evidence.",
            "medgemma_answer": claim,
            "extracted_claim": claim,
            "retrieved_documents": [ids[i] for i in ix],
            "gold_label": gold_label,
            "gold_evidence": gold_evidence,
            "source_healthver_id": row["id"],
            "annotation_type": "HealthVer verifier benchmark; answer is a proxy, not generated by MedGemma"
        })
    write(model_claims, out / "claims.jsonl")
    write(corpus, out / "corpus.jsonl")
    write(annotations, out / "gold_annotations.jsonl")
    (out / "README.md").write_text(
        "This 100-example set evaluates retrieval plus the frozen MultiVerS verifier.\n"
        "It is not a full MedGemma generation benchmark because the answer field is a\n"
        "HealthVer claim proxy. For end-to-end claims, replace it with manually checked\n"
        "MedGemma answers and claims.\n", encoding="utf-8")
    print(json.dumps({"claims": len(model_claims), "output_dir": str(out)}, indent=2))


if __name__ == "__main__": main()
